class Translator:
    def __init__(self, language="de"):
        self.language = language if language in ("de", "en") else "de"

    def __call__(self, key, **values):
        return TEXT[key][self.language == "en"].format(**values)

    def source(self, message):
        message = str(message)
        if self.language == "de":
            return message
        suffix = " Erneuter Versuch läuft automatisch."
        if message.endswith(suffix):
            return self.source(message[:-len(suffix)]) + " Retrying automatically."
        if message.startswith("LED-Steuerung: "):
            return "Lighting: " + self.source(message[len("LED-Steuerung: "):])
        if message.startswith("Das Otoskop meldet HTTP "):
            return message.replace("Das Otoskop meldet HTTP ", "The otoscope returned HTTP ", 1)
        if message.startswith("Kamera nicht gestartet: "):
            code = message[len("Kamera nicht gestartet: "):].split(".", 1)[0]
            return f"Camera failed to start: {code}. Check the Sense module and camera cable with the board powered off."
        return SOURCE.get(message, message)
